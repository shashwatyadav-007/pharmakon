from __future__ import annotations

from typing import Literal
from pydantic import BaseModel, Field, field_validator


class ChatMessage(BaseModel):
    """Single message turn in the AI conversation history."""

    role: Literal["user", "model", "assistant"] = Field(
        ...,
        description="Message role. Only 'user', 'model', or 'assistant' are permitted.",
    )
    content: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="Text content of the message turn.",
    )

    @field_validator("content")
    @classmethod
    def validate_content(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Message content cannot be empty or whitespace only.")
        return v.strip()


class ChatRequest(BaseModel):
    """Payload for POST /api/v1/ai/chat."""

    message: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="User question or query for the AI pharmacy assistant.",
    )
    history: list[ChatMessage] = Field(
        default_factory=list,
        max_length=20,
        description="Optional prior conversation turns for multi-turn context (max 20).",
    )

    @field_validator("message")
    @classmethod
    def validate_message(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Message cannot be empty or whitespace only.")
        return v.strip()


class ChatResponse(BaseModel):
    """Response payload containing assistant reply and execution metadata."""

    answer: str = Field(
        ...,
        description="Natural language answer generated by the assistant.",
    )
    history: list[ChatMessage] = Field(
        default_factory=list,
        description="Updated conversation history including user question and assistant answer.",
    )
    tools_used: list[str] = Field(
        default_factory=list,
        description="List of database tool names invoked during this turn.",
    )
